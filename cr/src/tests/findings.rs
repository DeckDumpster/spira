//! `cr finding` and `cr findings` through `cli::run`: a temp run and findings directory, a
//! scripted review repository, and a committer that records instead of running git.

use super::gh::{FakeGh, Shared, NAME, OWNER};
use super::{cfg, fixture, go, ports_with};
use crate::cli::Outcome;
use crate::ports::{Committer, Ports};
use crate::record;
use std::cell::RefCell;
use std::path::Path;
use std::rc::Rc;
use testkit::TempDir;

const SRC: &str = "demo/src/store.rs";

#[derive(Default)]
struct Commits(RefCell<Vec<(Vec<String>, String)>>);
struct SharedCommits(Rc<Commits>);

impl Committer for SharedCommits {
    fn commit(&self, _: &Path, paths: &[&str], message: &str) -> Result<(), String> {
        self.0 .0.borrow_mut().push((paths.iter().map(|s| s.to_string()).collect(), message.to_string()));
        Ok(())
    }
}

struct World {
    run: TempDir,
    out: TempDir,
    gh: Rc<FakeGh>,
    commits: Rc<Commits>,
    ports: Ports,
}

fn world() -> World {
    let run = TempDir::new("cr-find-run");
    let out = TempDir::new("cr-find-out");
    let gh = Rc::new(FakeGh::default());
    let commits = Rc::new(Commits::default());
    let mut ports = ports_with(fixture(), vec![], cfg());
    ports.run_dir = run.path().to_path_buf();
    ports.gh = Box::new(Shared(gh.clone()));
    ports.repo_owner = OWNER.into();
    ports.repo_name = NAME.into();
    ports.findings_dir = out.path().to_str().unwrap().to_string();
    ports.committer = Box::new(SharedCommits(commits.clone()));
    let w = World { run, out, gh, commits, ports };
    assert_eq!(w.cr(&["open", "--aim", SRC, "--seed", "3"]).code, 0);
    let mut r = record::load(w.run.path(), 1).unwrap();
    r.pr = Some(7);
    r.pr_url = Some("https://forge.invalid/o/r/pull/7".into());
    record::save(w.run.path(), &r).unwrap();
    w
}

impl World {
    fn cr(&self, args: &[&str]) -> Outcome {
        go(&self.ports, args)
    }
    fn finding(&mut self, json: &str) -> Outcome {
        self.ports.stdin = json.to_string();
        self.cr(&["finding", "--review", "001"])
    }
    fn page(&self, name: &str) -> String {
        std::fs::read_to_string(self.out.path().join(name)).unwrap()
    }
    fn write(&self, name: &str, text: &str) {
        std::fs::write(record::dir(self.run.path(), 1).join(name), text).unwrap();
    }
}

fn condemn(extra: &str) -> String {
    format!(r#"{{{extra}"words":"never hold the lock across a send","exemplar":{{"path":"{SRC}","line":6}},"kind":"condemn","rule":"A lock is not held across a send.","scope":"rust","became":{{"statutes":["law-no-lock-across-send"]}}}}"#)
}

const QUESTION: &str = r#"{"words":"why open?","exemplar":{"path":"demo/src/store.rs","line":3},"kind":"question","rule":"Open states its failure.","scope":"unit"}"#;

#[test]
fn recorded_findings_get_ids_and_land_on_the_page_and_only_a_pattern_in_the_catalogue() {
    let mut w = world();
    let a = w.finding(&condemn(""));
    assert_eq!((a.code, a.stdout.as_str()), (0, "001-1\n"), "{}", a.stderr);
    assert_eq!(w.finding(QUESTION).stdout, "001-2\n");
    let o = w.cr(&["findings", "--review", "001"]);
    assert_eq!(o.code, 0, "{}", o.stderr);
    let page = w.page("cr-001.md");
    for want in ["type: note", "review: 001", "source: c0ffee", "pr: https://forge.invalid/o/r/pull/7", "## 001-1", "## 001-2", "never hold the lock across a send", "demo/src/store.rs:6 @ c0ffee", "kind: question", "scope: rust", "law-no-lock-across-send", "Open states its failure."] {
        assert!(page.contains(want), "missing {want:?} in:\n{page}");
    }
    let cat = w.page("patterns.md");
    assert!(cat.contains("Generated by `cr findings`; edit the findings, not this page."));
    assert!(cat.contains("## Condemned") && cat.contains("A lock is not held across a send.") && cat.contains("demo/src/store.rs:6 @ c0ffee"), "{cat}");
    assert!(!cat.contains("Open states its failure."), "{cat}");
    assert_eq!(w.commits.0.borrow().len(), 1);
    assert_eq!(w.commits.0.borrow()[0].0, ["cr-001.md", "patterns.md"]);
}

#[test]
fn re_recording_an_id_replaces_the_finding_and_the_catalogue_does_not_duplicate_it() {
    let mut w = world();
    w.finding(&condemn(""));
    let again = condemn(r#""id":"001-1","#).replace(r#""statutes":["law-no-lock-across-send"]"#, r#""statutes":["law-no-lock-across-send"],"items":["sp-xyz123"]"#);
    assert_eq!(w.finding(&again).stdout, "001-1\n");
    w.cr(&["findings", "--review", "001"]);
    let page = w.page("cr-001.md");
    assert!(page.contains("sp-xyz123"), "{page}");
    assert_eq!(page.matches("## 001-").count(), 1);
    assert_eq!(w.page("patterns.md").matches("### A lock is not held across a send.").count(), 1);
}

#[test]
fn a_second_run_with_no_new_findings_commits_nothing() {
    let mut w = world();
    w.finding(&condemn(""));
    w.cr(&["findings", "--review", "001"]);
    let (page, cat) = (w.page("cr-001.md"), w.page("patterns.md"));
    w.cr(&["findings", "--review", "001"]);
    assert_eq!((w.page("cr-001.md"), w.page("patterns.md")), (page, cat));
    assert_eq!(w.commits.0.borrow().len(), 1);
}

#[test]
fn the_closeout_sorts_comments_into_agreed_only_you_and_only_the_concierge() {
    let mut w = world();
    w.finding(&condemn(""));
    w.write("sealed.json", &format!(r#"[{{"path":"{SRC}","line":3,"body":"C-agreed"}},{{"path":"{SRC}","line":8,"body":"C-alone"}}]"#));
    w.write(
        "comments.json",
        &format!(r#"[{{"path":"{SRC}","line":5,"body":"H-agreed","user":{{"type":"User"}}}},{{"path":"{SRC}","line":1,"body":"H-alone","user":{{"type":"User"}}}},{{"path":"{SRC}","line":3,"body":"B-bot","user":{{"type":"Bot"}}}}]"#),
    );
    let o = w.cr(&["findings", "--review", "001"]);
    assert_eq!(o.code, 0, "{}", o.stderr);
    let group = |name: &str| -> String {
        let at = o.stdout.find(&format!("### {name}")).unwrap();
        o.stdout[at..].split("\n###").next().unwrap().to_string()
    };
    assert!(group("Agreed").contains("C-agreed") && group("Agreed").contains("H-agreed"), "{}", o.stdout);
    assert!(group("Only you").contains("H-alone") && !group("Only you").contains("B-bot"), "{}", o.stdout);
    assert!(group("Only the Concierge").contains("C-alone"), "{}", o.stdout);
    assert!(o.stdout.contains("001-1 [condemn] A lock is not held across a send. → statute law-no-lock-across-send"), "{}", o.stdout);
}

#[test]
fn post_makes_one_forge_call_to_the_pull_requests_comments_with_the_closeout() {
    let mut w = world();
    w.finding(&condemn(""));
    w.gh.answer("issues/7/comments", r#"{"html_url":"https://forge.invalid/o/r/pull/7#c1"}"#);
    let o = w.cr(&["findings", "--review", "001", "--post"]);
    assert_eq!(o.code, 0, "{}", o.stderr);
    assert_eq!(w.gh.count(), 1);
    let posted = w.gh.posted(&format!("repos/{OWNER}/{NAME}/issues/7/comments"));
    assert_eq!(posted.len(), 1);
    assert!(posted[0]["body"].as_str().unwrap().contains("A lock is not held across a send."));
    assert!(o.stdout.contains("https://forge.invalid/o/r/pull/7#c1"));
}

#[test]
fn an_exemplar_outside_the_unit_or_past_the_end_of_its_file_is_refused() {
    let mut w = world();
    let o = w.finding(&condemn("").replace(SRC, "demo/src/net.rs"));
    assert_eq!(o.code, 2, "{}", o.stderr);
    let o = w.finding(&condemn("").replace(r#""line":6"#, r#""line":999"#));
    assert_eq!(o.code, 2, "{}", o.stderr);
    assert!(!record::dir(w.run.path(), 1).join("findings.jsonl").exists());
}

#[test]
fn an_empty_findings_directory_is_refused_by_name() {
    let mut w = world();
    w.finding(&condemn(""));
    w.ports.findings_dir = String::new();
    let o = w.cr(&["findings", "--review", "001"]);
    assert_eq!(o.code, 2);
    assert!(o.stderr.contains("SPIRA_CR_FINDINGS_DIR"), "{}", o.stderr);
}
