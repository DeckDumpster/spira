    std::fs::write(p.join("law/toc.toml"), toc_text).unwrap();
    let pointers_text = "version = 1\n\n[[retired]]\nslug = \"law-aeon-old\"\nreason = \"gone\"\nreplaced_by = \"law-one\"\non = \"2026-01-01\"\n"; // ffx-ok
