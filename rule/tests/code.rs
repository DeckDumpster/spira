//! The statute code: the generator's output, the drift check, append numbering, `enact --part`.

use std::collections::BTreeMap;
use std::path::Path;
use std::process::Command;

use rule::code::{append, drift, generate, parse_toc, render_toc, write_tree};

const TOC: &str = r#"[[part]]
number = 1
name = "Alpha"
slug = "alpha"
scope = "First scope."
slugs = [
  "law-one",
  "law-two",
]

[[part]]
number = 2
name = "Beta"
slug = "beta"
scope = "Second scope."
slugs = [
  "law-three",
]
"#;

fn book(slug: &str) -> Option<String> {
    match slug {
        "law-one" => Some("Do one. Then more.\n".into()),
        "law-two" => Some("Do two.".into()),
        "law-three" => Some("Do three. Always.\n".into()),
        _ => None,
    }
}

#[test]
fn three_statutes_in_two_parts_generate_the_expected_tree() {
    let parts = parse_toc(TOC).unwrap();
    let tree = generate(&parts, book);
    let want: BTreeMap<&str, &str> = BTreeMap::from([
        ("index.md", "# Statute code\n\n- Part 1 — Alpha — First scope.\n- Part 2 — Beta — Second scope.\n"),
        ("1-alpha/index.md", "# Part 1 — Alpha\n\nFirst scope.\n\n- §1.1 law-one — Do one.\n- §1.2 law-two — Do two.\n"),
        ("1-alpha/1.1-law-one.md", "# §1.1 law-one\n\nDo one. Then more.\n"),
        ("1-alpha/1.2-law-two.md", "# §1.2 law-two\n\nDo two.\n"),
        ("2-beta/index.md", "# Part 2 — Beta\n\nSecond scope.\n\n- §2.1 law-three — Do three.\n"),
        ("2-beta/2.1-law-three.md", "# §2.1 law-three\n\nDo three. Always.\n"),
    ]);
    let got: BTreeMap<&str, &str> = tree.iter().map(|(k, v)| (k.as_str(), v.as_str())).collect();
    assert_eq!(got, want);
}

#[test]
fn toc_renders_to_itself() {
    assert_eq!(render_toc(&parse_toc(TOC).unwrap()), TOC);
}

#[test]
fn a_hand_edit_or_a_stray_file_is_drift() {
    let parts = parse_toc(TOC).unwrap();
    let tree = generate(&parts, book);
    let dir = testkit::TempDir::new("law-drift");
    write_tree(&dir, TOC, &tree).unwrap();
    assert!(drift(&dir, &tree).is_empty());

    std::fs::write(dir.join("1-alpha/1.2-law-two.md"), "# §1.2 law-two\n\nDo two, edited.\n").unwrap();
    assert_eq!(drift(&dir, &tree), vec!["1-alpha/1.2-law-two.md: differs from what toc.toml generates"]);
    write_tree(&dir, TOC, &tree).unwrap();

    std::fs::write(dir.join("stray.md"), "x").unwrap();
    assert_eq!(drift(&dir, &tree), vec!["stray.md: not generated by toc.toml"]);
    write_tree(&dir, TOC, &tree).unwrap();
    assert!(drift(&dir, &tree).is_empty(), "write_tree must remove what the toc does not generate");

    std::fs::remove_file(dir.join("2-beta/index.md")).unwrap();
    assert_eq!(drift(&dir, &tree), vec!["2-beta/index.md: missing"]);
}

#[test]
fn append_adds_at_the_end_and_moves_nothing() {
    let parts = parse_toc(TOC).unwrap();
    let before = generate(&parts, book);
    let after = append(&parts, 1, "law-four").unwrap();
    assert_eq!(after[0].slugs, ["law-one", "law-two", "law-four"]);
    let grown = generate(&after, |s| book(s).or(Some("Four.".into())));
    for (path, body) in &before {
        if path != "index.md" && !path.ends_with("/index.md") {
            assert_eq!(grown.get(path), Some(body), "{path} moved");
        }
    }
    assert!(grown.contains_key("1-alpha/1.3-law-four.md"));
}

#[test]
fn append_refuses_an_unknown_part_and_a_slug_in_another_part() {
    let parts = parse_toc(TOC).unwrap();
    assert!(append(&parts, 9, "law-four").unwrap_err().contains("no Part 9"));
    assert!(append(&parts, 2, "law-one").unwrap_err().contains("Part 1"));
    assert_eq!(append(&parts, 1, "law-one").unwrap(), parts, "an amendment keeps its place");
}

#[test]
fn a_retired_slug_keeps_its_number() {
    let parts = parse_toc(TOC).unwrap();
    let tree = generate(&parts, |s| if s == "law-one" { None } else { book(s) });
    assert!(tree["1-alpha/1.1-law-one.md"].contains("[Reserved]"));
    assert!(tree.contains_key("1-alpha/1.2-law-two.md"));
}

#[test]
fn a_slug_in_two_parts_is_refused() {
    let bad = format!("{TOC}\n[[part]]\nnumber = 3\nname = \"C\"\nslug = \"c\"\nscope = \"s\"\nslugs = [\"law-one\"]\n");
    assert!(parse_toc(&bad).unwrap_err().contains("law-one"));
}

fn fixture_repo(tag: &str) -> testkit::TempDir {
    let dir = testkit::TempDir::new(tag);
    let git = |args: &[&str]| assert!(Command::new("git").arg("-C").arg(dir.path()).args(args).status().unwrap().success());
    git(&["init", "-q"]);
    std::fs::create_dir_all(dir.join("law")).unwrap();
    std::fs::write(dir.join("law/toc.toml"), TOC).unwrap();
    git(&["add", "-A"]);
    git(&["-c", "user.name=t", "-c", "user.email=t@t", "commit", "-q", "-m", "fixture"]);
    dir
}

fn rule_in(repo: &Path, args: &[&str]) -> std::process::Output {
    rule_from(repo, repo, args)
}

fn rule_from(cwd: &Path, repo: &Path, args: &[&str]) -> std::process::Output {
    let tmp = testkit::TempDir::new("rule-code-env");
    let db = tmp.join("db");
    std::fs::create_dir_all(db.join(".beads")).unwrap();
    let run = tmp.join("run");
    let toml = spira_config::process::fixture_toml(&tmp, &[("SPIRA_DB", &db.display().to_string()), ("SPIRA_RUN", &run.display().to_string())]);
    Command::new(env!("CARGO_BIN_EXE_rule"))
        .args(args)
        .current_dir(cwd)
        .env_clear()
        .env("SPIRA_REPO", repo)
        .env("PATH", "/usr/bin:/bin")
        .env("HOME", tmp.path())
        .env("SPIRA_TOML", &toml)
        .env("SPIRA_HOME", Path::new(env!("CARGO_MANIFEST_DIR")).join("../spira"))
        .output()
        .unwrap()
}

#[test]
fn enact_without_part_refuses_and_lists_the_parts() {
    let repo = fixture_repo("law-enact-nopart");
    let out = rule_in(&repo, &["enact", "newone", "Do four.", "--tool", "none", "--reason", "test"]);
    let err = String::from_utf8_lossy(&out.stderr);
    assert!(!out.status.success());
    assert!(err.contains("--part"), "{err}");
    assert!(err.contains("1 — Alpha: First scope.") && err.contains("2 — Beta: Second scope."), "{err}");
    let out = rule_in(&repo, &["enact", "newone", "Do four.", "--tool", "none", "--reason", "test", "--part", "9"]);
    assert!(!out.status.success());
    assert!(String::from_utf8_lossy(&out.stderr).contains("no Part 9"));
}

#[test]
fn code_check_reports_drift_and_code_repairs_it() {
    let repo = fixture_repo("law-code-cmd");
    let texts = testkit::TempDir::new("law-texts");
    for (s, t) in [("law-one", "Do one."), ("law-two", "Do two."), ("law-three", "Do three.")] {
        std::fs::write(texts.join(format!("{s}.txt")), t).unwrap();
    }
    let t = texts.display().to_string();
    assert!(!rule_in(&repo, &["code", "--check", "--texts", &t]).status.success(), "no tree yet is drift");
    assert!(rule_in(&repo, &["code", "--texts", &t]).status.success());
    assert!(rule_in(&repo, &["code", "--check", "--texts", &t]).status.success());
    std::fs::write(repo.join("law/index.md"), "edited").unwrap();
    assert!(!rule_in(&repo, &["code", "--check", "--texts", &t]).status.success());
}

#[test]
fn the_committed_tree_is_what_toc_toml_generates() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let toc = parse_toc(&std::fs::read_to_string(root.join("law/toc.toml")).unwrap()).unwrap();
    let seeds = root.join("spira/statutes");
    let text = |slug: &str| std::fs::read_to_string(seeds.join(format!("{slug}.txt"))).ok();
    let drift = drift(&root.join("law"), &generate(&toc, text));
    assert!(drift.is_empty(), "law/ differs from law/toc.toml — run `rule.sh code`: {drift:?}");
}

#[test]
fn enact_finds_the_repo_itself_and_leaves_the_callers_directory_alone() {
    let repo = fixture_repo("law-enact-away");
    let away = testkit::TempDir::new("law-enact-cwd");
    let out = rule_from(&away, &repo, &["enact", "newone", "Do four.", "--tool", "none", "--reason", "test", "--part", "2", "--dry-run"]);
    let err = String::from_utf8_lossy(&out.stderr);
    assert!(!err.contains("not inside a git checkout"), "{err}");
    assert!(std::fs::read_dir(away.path()).unwrap().next().is_none(), "the caller's directory was written to");
    let out = rule_from(&away, &repo, &["enact", "newone", "Do four.", "--tool", "none", "--reason", "test"]);
    assert!(!out.status.success());
    assert!(String::from_utf8_lossy(&out.stderr).contains("2 — Beta: Second scope."));
}

#[test]
fn commit_law_adds_the_section_on_its_own_branch_and_leaves_the_checkout_alone() {
    let repo = fixture_repo("law-commit-branch");
    let wt_root = testkit::TempDir::new("law-commit-wt");
    let toc = append(&parse_toc(TOC).unwrap(), 2, "law-four").unwrap();
    let book: BTreeMap<String, String> = [("law-one", "Do one."), ("law-two", "Do two."), ("law-three", "Do three."), ("law-four", "Do four.")]
        .into_iter()
        .map(|(k, v)| (k.to_string(), v.to_string()))
        .collect();
    let branch = rule::code::commit_law(repo.path(), None, wt_root.path(), "law-four", &toc, &book).unwrap();
    let show = |p: &str| Command::new("git").arg("-C").arg(repo.path()).args(["show", &format!("{branch}:{p}")]).output().unwrap();
    let added = show("law/2-beta/2.2-law-four.md");
    assert!(added.status.success() && String::from_utf8_lossy(&added.stdout).contains("Do four."));
    assert!(!repo.join("law/2-beta").exists(), "the checkout's own tree was written to");
    assert!(std::fs::read_dir(wt_root.path()).unwrap().next().is_none(), "the worktree was left behind");
}
